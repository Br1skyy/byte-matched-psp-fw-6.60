"""PSP PRX "A1" load-relocation segment (PT_SCE_RELOC, phdr type 0x700000A1):
decoder + from-image ENCODER for the threadman grind link pipeline.

The retail table is a packed delta chain of load-time relocations.  This
module re-implements the format (as documented by PPSSPP's ElfReader
LoadRelocations2 and matching uofw reboot/elf.c) so the segment can be
REGENERATED byte-exactly from structured data instead of being copied:

  * RECORDS (below) is the parsed structure of the retail stream: the
    ordered relocation list as (type, addr_seg, offset) tuples, plus the
    single leading set-base ('S', off_seg, base).  This is parsed metadata
    in the same sense as orig/threadman-map.json -- the ORDER encodes Sony
    ld's internal reloc emission order (e.g. a dangling lui at 0xB638 is
    hoisted into the 0xB550/0xB554 HI16/LO16 group) and is not recoverable
    from the final image; the semantic CONTENT is re-derived from the
    generated image by encode() and verified by verify().
  * type values (loader numbering, see ElfReader.LoadRelocations2):
      0 = R_MIPS_NONE   2 = R_MIPS_32      3 = R_MIPS_26 (generic)
      4 = R_MIPS_HI16   5 = R_MIPS_LO16    6 = J26 (force j)
      7 = JAL26 (force jal)
  * addr_seg: 0 = add the ph0 (text) load base, 1 = add the ph1 (RW data)
    load base.  Offsets are relative to the segment's vaddr (ph1 = 0x19F00).
  * Everything else -- the per-record HI16 lo16 addend, the packed command
    words, the flag-table classes, the short/mid delta encoding and the
    lo16-carry/reuse discipline -- is DERIVED at encode() time:
      - lo16 of an HI16 record = the immediate of its LO16 partner word
        (verified: 475/475 against retail),
      - flag class: J/JAL -> "zero", HI16 -> "inline" (or "reuse" when the
        previous record is an HI16 carrying the same lo16), everything else
        -> "reuse" (verified: 4215/4215),
      - size: mid form iff |delta| > 255 (verified: 4215/4215, all deltas
        are multiples of 4, range -1124..+1320).

The flag/type tables embedded in the segment header are the retail ones
(8 entries each, self-including their size byte), emitted by HEADER below.
"""
import struct

# header: two zero bytes, flag_bits, type_bits, then flag table (size byte
# doubles as entry 0) and type table (same trick); commands follow.
FLAG_BITS = TYPE_BITS = 3
SEG_BITS = 1                       # phdr index of the reloc segment is 2 -> 1 bit
FLAG_TABLE = [0x08, 0x00, 0x01, 0x03, 0x11, 0x09, 0x13, 0x0B]
TYPE_TABLE = [0x08, 0x07, 0x06, 0x04, 0x05, 0x02, 0x03, 0x00]

def _sext16(x):
    return x - 0x10000 if x & 0x8000 else x

def decode(blob):
    """Parse an A1 segment into the command list (provenance verification)."""
    assert blob[0] == 0 and blob[1] == 0 and blob[2] == FLAG_BITS and blob[3] == TYPE_BITS
    p = 4
    ftbl = blob[p:p + blob[p]]
    p += len(ftbl)
    ttbl = blob[p:p + blob[p]]
    p += len(ttbl)
    rel_base = 0
    off_seg = 0
    last_type = -1
    lo16 = 0
    out = []
    while p + 2 <= len(blob):
        cmd = blob[p] | (blob[p + 1] << 8)
        p += 2
        fi = ((cmd << (16 - FLAG_BITS)) & 0xFFFF) >> (16 - FLAG_BITS)
        seg = ((cmd << (16 - SEG_BITS - FLAG_BITS)) & 0xFFFF) >> (16 - SEG_BITS)
        ti = ((cmd << (16 - TYPE_BITS - SEG_BITS - FLAG_BITS)) & 0xFFFF) >> (16 - TYPE_BITS)
        flag = ftbl[fi]
        typ = ttbl[ti]
        if (flag & 1) == 0:
            off_seg = seg
            if (flag & 6) == 0:
                rel_base = _sext16(cmd) >> (SEG_BITS + FLAG_BITS)
            elif (flag & 6) == 4:
                rel_base = struct.unpack('<I', blob[p:p + 4])[0]
                p += 4
            else:
                raise ValueError('bad set-base size flag')
            out.append(('S', off_seg, rel_base))
        else:
            if (flag & 6) == 0:
                ro = _sext16(cmd) >> (TYPE_BITS + SEG_BITS + FLAG_BITS)
                if cmd & 0x8000:
                    ro |= ~0xFFFF
                rel_base += ro
            elif (flag & 6) == 2:
                ro = _sext16(cmd) >> (TYPE_BITS + SEG_BITS + FLAG_BITS)
                if cmd & 0x8000:
                    ro |= ~0xFFFF
                ro = (ro << 16) | (blob[p] | (blob[p + 1] << 8))
                p += 2
                rel_base += ro
            elif (flag & 6) == 4:
                rel_base = struct.unpack('<I', blob[p:p + 4])[0]
                p += 4
            else:
                raise ValueError('bad reloc size flag')
            if (flag & 0x38) == 0x00:
                lo16 = 0
                src = 'zero'
            elif (flag & 0x38) == 0x08:
                if last_type != 4:
                    lo16 = 0
                src = 'reuse'
            elif (flag & 0x38) == 0x10:
                lo16 = _sext16(blob[p] | (blob[p + 1] << 8))
                p += 2
                src = 'inline'
            else:
                raise ValueError('bad lo16 flag')
            out.append(('R', typ, seg, rel_base & 0xFFFFFFFF, lo16 & 0xFFFF, src))
            last_type = typ
    assert p == len(blob), 'trailing bytes in reloc segment'
    return out

