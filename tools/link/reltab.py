def _word(image, off):
    return struct.unpack('<I', image[off:off + 4])[0]

def encode(records, image):
    """Emit the A1 relocation segment for `records` against the generated
    `image` (ph0 bytes).

    lo16 addends are derived from the image: for the HI16 record at stream
    index i the partner is the first LO16 record at some j > i (Sony ld
    groups HI16s -- even one from EARLIER in address order -- ahead of the
    shared LO16); the partner word's immediate is the pair's lo value."""
    next_lo = [len(records)] * (len(records) + 1)
    for i in range(len(records) - 1, -1, -1):
        if records[i][0] == 5:
            next_lo[i] = i
        else:
            next_lo[i] = next_lo[i + 1]
    out = bytearray()
    out += bytes([0, 0, FLAG_BITS, TYPE_BITS])
    out += bytes(FLAG_TABLE)                 # size byte doubles as entry 0
    out += bytes(TYPE_TABLE)
    ti_of = {}
    for i, v in enumerate(TYPE_TABLE):
        ti_of.setdefault(v, i)
    prev_off = prev_typ = prev_lo = None
    for idx, rec in enumerate(records):
        if rec[0] == 'S':
            _, seg, base = rec
            cmd = ((base & 0xFFF) << (SEG_BITS + FLAG_BITS)) | (seg << FLAG_BITS) | 1
            out += struct.pack('<H', cmd)
            prev_off = None                  # set-base resets the chain
            continue
        typ, aseg, off = rec
        delta = off if prev_off is None else off - prev_off
        assert delta % 4 == 0, (rec, delta)
        if typ == 4:                         # HI16: lo16 from partner imm
            j = next_lo[idx + 1]
            assert j < len(records), 'HI16 without following LO16'
            lo16 = _word(image, records[j][2]) & 0xFFFF
        else:
            lo16 = 0
        mid = not (-255 <= delta <= 255)
        if typ in (6, 7):
            cls = 0                          # zero
        elif typ == 4:
            cls = 2 if (prev_typ == 4 and prev_lo == lo16) else 1
        else:
            cls = 2                          # reuse
        fi = {(0, False): 2, (0, True): 3, (1, False): 4, (1, True): 6,
              (2, False): 5, (2, True): 7}[(cls, mid)]
        ti = ti_of[typ]
        assert fi < 8 and ti < 8
        if not mid:
            cmd = ((delta & 0x1FF) << (TYPE_BITS + SEG_BITS + FLAG_BITS)) | \
                  (ti << (SEG_BITS + FLAG_BITS)) | (aseg << FLAG_BITS) | fi
            out += struct.pack('<H', cmd)
            if cls == 1:                     # inline lo16
                out += struct.pack('<H', lo16)
        else:
            cmd = (((delta >> 16) & 0x1FF) << (TYPE_BITS + SEG_BITS + FLAG_BITS)) | \
                  (ti << (SEG_BITS + FLAG_BITS)) | (aseg << FLAG_BITS) | fi
            out += struct.pack('<H', cmd)
            out += struct.pack('<H', delta & 0xFFFF)
            if cls == 1:
                out += struct.pack('<H', lo16)
        prev_off, prev_typ, prev_lo = off, typ, lo16
    return bytes(out)

def verify(records, image, seg_end, func_starts):
    """Semantic verification of the inventory against the generated image.
    Returns a list of human-readable anomaly strings (empty = clean)."""
    bad = []
    counts = {}
    for rec in records:
        if rec[0] == 'S':
            continue
        typ, aseg, off = rec
        counts[typ] = counts.get(typ, 0) + 1
        if off % 4 or off + 4 > seg_end:
            bad.append('misaligned/out-of-range offset 0x%X' % off)
            continue
        w = _word(image, off)
        op = w >> 26
        if typ == 4 and op != 0x0F:
            bad.append('HI16 on non-lui @0x%X (op %02X)' % (off, op))
        if typ == 6 and op != 2:
            bad.append('J26 on non-j @0x%X' % off)
        if typ == 7 and op != 3:
            bad.append('JAL26 on non-jal @0x%X' % off)
        if typ in (5,) and op == 0x0F:
            bad.append('LO16 on lui @0x%X' % off)
    # every j/jal in text must be covered exactly once
    jj = {i * 4 for i in range(seg_end // 4)
          if i * 4 < 0x1868C and (_word(image, i * 4) >> 26) in (2, 3)}
    have = {r[2] for r in records if r[0] != 'S' and r[1] == 0 and r[0] in (6, 7)}
    for a in sorted(jj - have):
        bad.append('j/jal at 0x%X missing from records' % a)
    for a in sorted(have - jj):
        bad.append('record at 0x%X not a j/jal' % a)
    return bad, counts
